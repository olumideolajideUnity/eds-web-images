using UnityEditor; using UnityEngine; using UnityEngine.ProBuilder; using UnityEngine.ProBuilder.MeshOperations; using UnityEditor.ProBuilder; using System.Linq; using System.Reflection;
var BF = BindingFlags.Instance|BindingFlags.Static|BindingFlags.Public|BindingFlags.NonPublic;
var a = System.AppDomain.CurrentDomain.GetAssemblies().First(x => x.GetName().Name == "Unity.ProBuilder.Editor");
var act = System.Activator.CreateInstance(a.GetType("UnityEditor.ProBuilder.Actions.BevelEdges"));
var pref = act.GetType().GetField("m_BevelSize", BF).GetValue(act);
pref.GetType().GetMethod("SetValue", BF, null, new[]{ typeof(float), typeof(bool) }, null)?.Invoke(pref, new object[]{ 0.68f, true });
var pb = GameObject.Find("Box").GetComponent<ProBuilderMesh>();
var top = pb.faces.OrderByDescending(f => f.indexes.Average(i => pb.positions[i].y)).First();
var edge = top.edges.OrderByDescending(e => pb.positions[e.a].x + pb.positions[e.b].x).First();
var faces = Bevel.BevelEdges(pb, new[]{ edge }, 0.68f);
pb.ToMesh(); pb.Refresh();
ProBuilderEditor.selectMode = SelectMode.Face;
pb.SetSelectedFaces(faces);
ProBuilderEditor.Refresh();
Tools.current = Tool.Move;
var sv = Resources.FindObjectsOfTypeAll<SceneView>().First(w => !w.docked);
sv.LookAtDirect(new Vector3(0.2f, 0.4f, -0.4f), Quaternion.Euler(30f, -62f, 0f), 4.3f);
SceneView.RepaintAll();
return "bevelFaces=" + faces?.Count + " size=" + pref.GetType().GetProperty("value", BF)?.GetValue(pref);
