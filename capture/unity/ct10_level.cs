using UnityEditor; using UnityEngine; using System.Linq;
Selection.activeGameObject = GameObject.Find("Camera");
var sv = Resources.FindObjectsOfTypeAll<SceneView>().First(w => !w.docked);
var rot = Quaternion.Euler(24f, 62f, 0f);
sv.LookAtDirect(new Vector3(-0.2f, 1.4f, -0.8f) + rot * Vector3.right * 2.9f, rot, 5.3f);
var co = sv.overlayCanvas.overlays.First(o => o.displayName == "Cameras");
co.displayed = true; co.Undock(); co.collapsed = false; co.floatingPosition = new Vector2(930, 175);
Selection.activeGameObject = null;
sv.Repaint();
return "ok";
